#!/usr/bin/env bash
# Lab-only logging HTTP proxy for Cursor Cloud Agent startup.
# CONNECT-level logging (host:port). TLS is tunneled, not intercepted.
#
#   install  apt-install tinyproxy, nftables, and redsocks; persist proxy env
#   start    start tinyproxy and force tcp/80 and tcp/443 through it
#
# Called from .cursor/environment.json. The Dockerfile copies this file to
# /usr/local/bin/egress-proxy.sh and start runs that copy:
#   install runs once per environment build
#   start runs detached on every agent boot (bash -l, not awaited)
#
# Force path: nft dnat sends new tcp/80 and tcp/443, except the tinyproxy
# user, to redsocks. redsocks reads the original destination and opens
# HTTP CONNECT to tinyproxy, which logs it and dials out. This kernel has
# no iptables LOG or owner match, and tinyproxy's transparent mode cannot
# splice TLS. `iptables -F` does not remove this nft table.
#
# Exports in this process do not reach the already-running agent.
# Login shells pick them up from /etc/profile.d/egress-proxy.sh.
# PAM sessions also see /etc/environment. Interactive bash sources the
# same file via a marked block at the top of the bashrc files.
# Non-interactive, non-login shells (the agent tool shell) do not source
# those files unless this process's environment already has the variables.

set -euo pipefail

PROXY_PORT=8888
PROXY_URL="http://127.0.0.1:${PROXY_PORT}"
REDSOCKS_PORT=12345
LOG_DIR=/tmp/egress
LOG_FILE="${LOG_DIR}/proxy.log"
PID_FILE="${LOG_DIR}/tinyproxy.pid"
CONF_FILE="${LOG_DIR}/tinyproxy.conf"
REDSOCKS_CONF="${LOG_DIR}/redsocks.conf"
REDSOCKS_LOG="${LOG_DIR}/redsocks.log"
NFT_FAMILY=ip
NFT_TABLE=egresslab
PROFILE_FILE=/etc/profile.d/egress-proxy.sh
ENV_FILE=/etc/environment
MARKER_BEGIN="# BEGIN egress-proxy-lab"
MARKER_END="# END egress-proxy-lab"

log() {
  printf '%s\n' "$*"
}

need_sudo() {
  if ! sudo -n true 2>/dev/null; then
    log "sudo is required and passwordless sudo is not available"
    exit 1
  fi
}

install_packages() {
  local missing=()
  command -v tinyproxy >/dev/null 2>&1 || missing+=(tinyproxy)
  command -v nft >/dev/null 2>&1 || missing+=(nftables)
  command -v redsocks >/dev/null 2>&1 || missing+=(redsocks)
  if [[ ${#missing[@]} -eq 0 ]]; then
    log "tinyproxy, nft, and redsocks already installed"
    return 0
  fi
  need_sudo
  log "installing from apt: ${missing[*]}"
  # Keep apt off the proxy if a previous attempt exported it in this shell.
  sudo -n env \
    DEBIAN_FRONTEND=noninteractive \
    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
    apt-get update
  # The package's init script may fail because PID 1 is tini, not systemd.
  # Keep going when the binaries are actually installed.
  if ! sudo -n env \
    DEBIAN_FRONTEND=noninteractive \
    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
    apt-get install -y "${missing[@]}"; then
    local cmd
    for cmd in tinyproxy nft redsocks; do
      if ! command -v "$cmd" >/dev/null 2>&1; then
        log "apt-get install failed; missing ${cmd}"
        exit 1
      fi
    done
    log "apt-get install returned non-zero; binaries are present, continuing"
  fi
  log "installed: tinyproxy=$(command -v tinyproxy) nft=$(command -v nft) redsocks=$(command -v redsocks)"
}

write_config() {
  mkdir -p "$LOG_DIR"
  chmod 755 "$LOG_DIR"
  need_sudo
  # sudo touch: on a later start these files are owned by the tinyproxy user.
  sudo -n touch "$LOG_FILE" "$PID_FILE"
  cat >"$CONF_FILE" <<EOF
# Generated by .cursor/egress-proxy.sh. Do not edit by hand.
# Listen on loopback only. CONNECT is logged; TLS is not decrypted.
Port ${PROXY_PORT}
Listen 127.0.0.1
Timeout 600
LogFile "${LOG_FILE}"
LogLevel Connect
PidFile "${PID_FILE}"
MaxClients 50
Allow 127.0.0.1
Allow ::1
DisableViaHeader Yes
ConnectPort 80
ConnectPort 443
EOF
  chmod 644 "$CONF_FILE"
  # The daemon runs as the tinyproxy user, which must be able to rewrite
  # the log and pid, while this script (ubuntu) must still be able to read them.
  sudo -n chown tinyproxy:tinyproxy "$LOG_FILE" "$PID_FILE"
  sudo -n chmod 644 "$LOG_FILE" "$PID_FILE"
}

write_redsocks_config() {
  mkdir -p "$LOG_DIR"
  need_sudo
  sudo -n touch "$REDSOCKS_LOG"
  # redsocks opens the log as root, then drops to the redsocks user.
  sudo -n chown redsocks:redsocks "$REDSOCKS_LOG"
  sudo -n chmod 644 "$REDSOCKS_LOG"
  cat >"$REDSOCKS_CONF" <<EOF
base {
    log_debug = off;
    log_info = on;
    log = "file:${REDSOCKS_LOG}";
    daemon = on;
    user = redsocks;
    group = redsocks;
    redirector = iptables;
}
redsocks {
    local_ip = 127.0.0.1;
    local_port = ${REDSOCKS_PORT};
    ip = 127.0.0.1;
    port = ${PROXY_PORT};
    type = http-connect;
}
EOF
  chmod 644 "$REDSOCKS_CONF"
}

write_profile() {
  need_sudo
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<EOF
# Generated by .cursor/egress-proxy.sh. Lab logging proxy for new login shells.
export http_proxy="${PROXY_URL}"
export https_proxy="${PROXY_URL}"
export HTTP_PROXY="${PROXY_URL}"
export HTTPS_PROXY="${PROXY_URL}"
export no_proxy="localhost,127.0.0.1"
export NO_PROXY="localhost,127.0.0.1"
EOF
  sudo -n cp "$tmp" "$PROFILE_FILE"
  sudo -n chmod 644 "$PROFILE_FILE"
  rm -f "$tmp"
  log "wrote ${PROFILE_FILE}"
}

upsert_environment_file() {
  need_sudo
  local tmp key value
  tmp="$(mktemp)"
  if [[ -f "$ENV_FILE" ]]; then
    # Drop any previous proxy keys this script owns, keep the rest.
    grep -vE '^(http_proxy|https_proxy|HTTP_PROXY|HTTPS_PROXY|no_proxy|NO_PROXY)=' "$ENV_FILE" >"$tmp" || true
  else
    : >"$tmp"
  fi
  {
    printf '\n'
    printf 'http_proxy="%s"\n' "$PROXY_URL"
    printf 'https_proxy="%s"\n' "$PROXY_URL"
    printf 'HTTP_PROXY="%s"\n' "$PROXY_URL"
    printf 'HTTPS_PROXY="%s"\n' "$PROXY_URL"
    printf 'no_proxy="localhost,127.0.0.1"\n'
    printf 'NO_PROXY="localhost,127.0.0.1"\n'
  } >>"$tmp"
  sudo -n cp "$tmp" "$ENV_FILE"
  sudo -n chmod 644 "$ENV_FILE"
  rm -f "$tmp"
  log "updated ${ENV_FILE}"
}

inject_bashrc() {
  local file="$1"
  [[ -f "$file" ]] || return 0
  if grep -qF "$MARKER_BEGIN" "$file"; then
    return 0
  fi
  local tmp
  tmp="$(mktemp)"
  {
    printf '%s\n' "$MARKER_BEGIN"
    printf '%s\n' '[ -f /etc/profile.d/egress-proxy.sh ] && . /etc/profile.d/egress-proxy.sh'
    printf '%s\n' "$MARKER_END"
    printf '\n'
    cat "$file"
  } >"$tmp"
  if [[ -w "$file" ]]; then
    cp "$tmp" "$file"
  else
    need_sudo
    sudo -n cp "$tmp" "$file"
  fi
  rm -f "$tmp"
  log "injected proxy env into ${file}"
}

write_shell_env() {
  write_profile
  upsert_environment_file
  inject_bashrc /etc/bash.bashrc
  inject_bashrc "${HOME}/.bashrc"
  # Export for children of this process. A detached start cannot change
  # the environment of the agent that launched it.
  # shellcheck disable=SC1090
  set -a
  # shellcheck disable=SC1091
  . "$PROFILE_FILE"
  set +a
}

proxy_pid() {
  [[ -f "$PID_FILE" ]] || return 1
  local pid
  if [[ -r "$PID_FILE" ]]; then
    pid="$(tr -d '[:space:]' <"$PID_FILE" || true)"
  else
    need_sudo
    pid="$(sudo -n cat "$PID_FILE" | tr -d '[:space:]' || true)"
  fi
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  if [[ -d "/proc/${pid}" ]]; then
    printf '%s\n' "$pid"
    return 0
  fi
  return 1
}

wait_for_port() {
  local port="$1"
  local i
  for i in $(seq 1 50); do
    if python3 - "$port" <<'PY'
import socket, sys
port = int(sys.argv[1])
s = socket.socket()
s.settimeout(0.2)
try:
    s.connect(("127.0.0.1", port))
except OSError:
    sys.exit(1)
finally:
    s.close()
PY
    then
      return 0
    fi
    sleep 0.1
  done
  return 1
}

stop_pid() {
  local pid="$1"
  sudo -n kill "$pid" 2>/dev/null || true
  local i
  for i in $(seq 1 50); do
    [[ -d "/proc/${pid}" ]] || return 0
    sleep 0.1
  done
  sudo -n kill -9 "$pid" 2>/dev/null || true
}

start_proxy() {
  local want_uid pid uid
  want_uid="$(id -u tinyproxy)"
  write_config
  if pid="$(proxy_pid)"; then
    uid="$(ps -o uid= -p "$pid" | tr -d '[:space:]')"
    if [[ "$uid" == "$want_uid" ]]; then
      log "tinyproxy already running pid=${pid} uid=${uid}"
      return 0
    fi
    log "stopping tinyproxy pid=${pid} uid=${uid}; force path needs uid=${want_uid}"
    stop_pid "$pid"
    sudo -n rm -f "$PID_FILE"
  fi
  # The packaged unit is not usable here: PID 1 is tini, not systemd.
  if command -v service >/dev/null 2>&1; then
    sudo -n service tinyproxy stop >/dev/null 2>&1 || true
  fi
  log "starting tinyproxy on ${PROXY_URL} as uid=${want_uid}"
  # Daemonizes unless -d is passed. Stderr is kept for install failures.
  # Run as the tinyproxy user so nft can exclude only the proxy's own dials.
  sudo -n -u tinyproxy tinyproxy -c "$CONF_FILE" 2>"${LOG_DIR}/tinyproxy.stderr" || {
    log "tinyproxy failed to start"
    if [[ -s "${LOG_DIR}/tinyproxy.stderr" ]]; then
      cat "${LOG_DIR}/tinyproxy.stderr" >&2
    fi
    exit 1
  }
  if ! wait_for_port "$PROXY_PORT"; then
    log "tinyproxy did not open 127.0.0.1:${PROXY_PORT}"
    if [[ -s "${LOG_DIR}/tinyproxy.stderr" ]]; then
      cat "${LOG_DIR}/tinyproxy.stderr" >&2
    fi
    if [[ -f "$LOG_FILE" ]]; then
      tail -n 40 "$LOG_FILE" >&2 || true
    fi
    exit 1
  fi
  pid="$(proxy_pid || true)"
  log "tinyproxy listening pid=${pid:-unknown} log=${LOG_FILE}"
}

start_redsocks() {
  local pid pids
  write_redsocks_config
  pids="$(pgrep -u redsocks -x redsocks || true)"
  if [[ -n "$pids" ]]; then
    log "stopping existing redsocks pid=${pids//$'\n'/ }"
    for pid in $pids; do
      stop_pid "$pid"
    done
  fi
  log "starting redsocks on 127.0.0.1:${REDSOCKS_PORT} -> ${PROXY_URL}"
  sudo -n redsocks -c "$REDSOCKS_CONF" || {
    log "redsocks failed to start"
    if [[ -s "$REDSOCKS_LOG" ]]; then
      tail -n 40 "$REDSOCKS_LOG" >&2 || true
    fi
    exit 1
  }
  if ! wait_for_port "$REDSOCKS_PORT"; then
    log "redsocks did not open 127.0.0.1:${REDSOCKS_PORT}"
    if [[ -s "$REDSOCKS_LOG" ]]; then
      tail -n 40 "$REDSOCKS_LOG" >&2 || true
    fi
    exit 1
  fi
  pids="$(pgrep -u redsocks -x redsocks || true)"
  log "redsocks listening pid=${pids//$'\n'/ } log=${REDSOCKS_LOG}"
}

clear_force_rules() {
  need_sudo
  sudo -n nft delete table "$NFT_FAMILY" "$NFT_TABLE" 2>/dev/null || true
}

apply_force_rules() {
  local uid
  uid="$(id -u tinyproxy)"
  need_sudo
  clear_force_rules
  sudo -n nft add table "$NFT_FAMILY" "$NFT_TABLE"
  sudo -n nft add chain "$NFT_FAMILY" "$NFT_TABLE" output '{ type nat hook output priority dstnat; policy accept; }'
  sudo -n nft add rule "$NFT_FAMILY" "$NFT_TABLE" output tcp dport '{ 80, 443 }' \
    meta skuid != "$uid" counter dnat to "127.0.0.1:${REDSOCKS_PORT}"
  log "nft dnat: new tcp/80,443 except uid ${uid} -> 127.0.0.1:${REDSOCKS_PORT}"
}

usage() {
  log "usage: $0 {install|start}"
  exit 2
}

main() {
  local cmd="${1:-}"
  case "$cmd" in
    install)
      install_packages
      write_shell_env
      log "install complete"
      ;;
    start)
      install_packages
      write_shell_env
      # Remove a previous boot's force rule before restarting helpers so a
      # failed start cannot black-hole tcp/80 and tcp/443.
      clear_force_rules
      start_proxy
      start_redsocks
      apply_force_rules
      log "start complete"
      ;;
    *)
      usage
      ;;
  esac
}

main "$@"
