#!/usr/bin/env bash
# Lab-only logging HTTP proxy for Cursor Cloud Agent startup.
# CONNECT-level logging (host:port). TLS is tunneled, not intercepted.
#
#   install  apt-install tinyproxy and persist proxy env for new shells
#   start    start tinyproxy in the background (also installs if missing)
#
# Called from .cursor/environment.json:
#   install runs once per environment build
#   start runs detached on every agent boot (bash -l, not awaited)
#
# Exports in this process do not reach the already-running agent.
# Login shells pick them up from /etc/profile.d/egress-proxy.sh.
# PAM sessions also see /etc/environment. Interactive bash sources the
# same file via a marked block at the top of the bashrc files.
# Non-interactive, non-login shells (the agent tool shell) do not source
# those files unless this process's environment already has the variables.

set -euo pipefail

PROXY_PORT=8888
PROXY_URL="http://127.0.0.1:${PROXY_PORT}"
LOG_DIR=/tmp/egress
LOG_FILE="${LOG_DIR}/proxy.log"
PID_FILE="${LOG_DIR}/tinyproxy.pid"
CONF_FILE="${LOG_DIR}/tinyproxy.conf"
PROFILE_FILE=/etc/profile.d/egress-proxy.sh
ENV_FILE=/etc/environment
MARKER_BEGIN="# BEGIN egress-proxy-lab"
MARKER_END="# END egress-proxy-lab"

log() {
  printf '%s\n' "$*"
}

need_sudo() {
  if ! sudo -n true 2>/dev/null; then
    log "sudo is required and passwordless sudo is not available"
    exit 1
  fi
}

install_tinyproxy() {
  if command -v tinyproxy >/dev/null 2>&1; then
    log "tinyproxy already installed: $(command -v tinyproxy)"
    return 0
  fi
  need_sudo
  log "installing tinyproxy from apt"
  # Keep apt off the proxy if a previous attempt exported it in this shell.
  sudo -n env \
    DEBIAN_FRONTEND=noninteractive \
    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
    apt-get update
  # The package's init script may fail because PID 1 is tini, not systemd.
  # Keep going when the binary is actually installed.
  if ! sudo -n env \
    DEBIAN_FRONTEND=noninteractive \
    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
    apt-get install -y tinyproxy; then
    if ! command -v tinyproxy >/dev/null 2>&1; then
      log "apt-get install tinyproxy failed"
      exit 1
    fi
    log "apt-get install returned non-zero; tinyproxy binary is present, continuing"
  fi
  log "tinyproxy installed: $(command -v tinyproxy)"
}

write_config() {
  mkdir -p "$LOG_DIR"
  touch "$LOG_FILE"
  chmod 755 "$LOG_DIR"
  chmod 644 "$LOG_FILE"
  cat >"$CONF_FILE" <<EOF
# Generated by .cursor/egress-proxy.sh. Do not edit by hand.
# Listen on loopback only. CONNECT is logged; TLS is not decrypted.
Port ${PROXY_PORT}
Listen 127.0.0.1
Timeout 600
LogFile "${LOG_FILE}"
LogLevel Connect
PidFile "${PID_FILE}"
MaxClients 50
Allow 127.0.0.1
Allow ::1
DisableViaHeader Yes
ConnectPort 80
ConnectPort 443
EOF
}

write_profile() {
  need_sudo
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<EOF
# Generated by .cursor/egress-proxy.sh. Lab logging proxy for new login shells.
export http_proxy="${PROXY_URL}"
export https_proxy="${PROXY_URL}"
export HTTP_PROXY="${PROXY_URL}"
export HTTPS_PROXY="${PROXY_URL}"
export no_proxy="localhost,127.0.0.1"
export NO_PROXY="localhost,127.0.0.1"
EOF
  sudo -n cp "$tmp" "$PROFILE_FILE"
  sudo -n chmod 644 "$PROFILE_FILE"
  rm -f "$tmp"
  log "wrote ${PROFILE_FILE}"
}

upsert_environment_file() {
  need_sudo
  local tmp key value
  tmp="$(mktemp)"
  if [[ -f "$ENV_FILE" ]]; then
    # Drop any previous proxy keys this script owns, keep the rest.
    grep -vE '^(http_proxy|https_proxy|HTTP_PROXY|HTTPS_PROXY|no_proxy|NO_PROXY)=' "$ENV_FILE" >"$tmp" || true
  else
    : >"$tmp"
  fi
  {
    printf '\n'
    printf 'http_proxy="%s"\n' "$PROXY_URL"
    printf 'https_proxy="%s"\n' "$PROXY_URL"
    printf 'HTTP_PROXY="%s"\n' "$PROXY_URL"
    printf 'HTTPS_PROXY="%s"\n' "$PROXY_URL"
    printf 'no_proxy="localhost,127.0.0.1"\n'
    printf 'NO_PROXY="localhost,127.0.0.1"\n'
  } >>"$tmp"
  sudo -n cp "$tmp" "$ENV_FILE"
  sudo -n chmod 644 "$ENV_FILE"
  rm -f "$tmp"
  log "updated ${ENV_FILE}"
}

inject_bashrc() {
  local file="$1"
  [[ -f "$file" ]] || return 0
  if grep -qF "$MARKER_BEGIN" "$file"; then
    return 0
  fi
  local tmp
  tmp="$(mktemp)"
  {
    printf '%s\n' "$MARKER_BEGIN"
    printf '%s\n' '[ -f /etc/profile.d/egress-proxy.sh ] && . /etc/profile.d/egress-proxy.sh'
    printf '%s\n' "$MARKER_END"
    printf '\n'
    cat "$file"
  } >"$tmp"
  if [[ -w "$file" ]]; then
    cp "$tmp" "$file"
  else
    need_sudo
    sudo -n cp "$tmp" "$file"
  fi
  rm -f "$tmp"
  log "injected proxy env into ${file}"
}

write_shell_env() {
  write_profile
  upsert_environment_file
  inject_bashrc /etc/bash.bashrc
  inject_bashrc "${HOME}/.bashrc"
  # Export for children of this process. A detached start cannot change
  # the environment of the agent that launched it.
  # shellcheck disable=SC1090
  set -a
  # shellcheck disable=SC1091
  . "$PROFILE_FILE"
  set +a
}

proxy_pid() {
  [[ -f "$PID_FILE" ]] || return 1
  local pid
  pid="$(tr -d '[:space:]' <"$PID_FILE" || true)"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  if [[ -d "/proc/${pid}" ]]; then
    printf '%s\n' "$pid"
    return 0
  fi
  return 1
}

wait_for_port() {
  local i
  for i in $(seq 1 50); do
    if python3 - "$PROXY_PORT" <<'PY'
import socket, sys
port = int(sys.argv[1])
s = socket.socket()
s.settimeout(0.2)
try:
    s.connect(("127.0.0.1", port))
except OSError:
    sys.exit(1)
finally:
    s.close()
PY
    then
      return 0
    fi
    sleep 0.1
  done
  return 1
}

start_proxy() {
  write_config
  if pid="$(proxy_pid)"; then
    log "tinyproxy already running pid=${pid}"
    return 0
  fi
  rm -f "$PID_FILE"
  # The packaged unit is not usable here: PID 1 is tini, not systemd.
  if command -v service >/dev/null 2>&1; then
    sudo -n service tinyproxy stop >/dev/null 2>&1 || true
  fi
  log "starting tinyproxy on ${PROXY_URL}"
  # Daemonizes unless -d is passed. Stderr is kept for install failures.
  tinyproxy -c "$CONF_FILE" 2>"${LOG_DIR}/tinyproxy.stderr" || {
    log "tinyproxy failed to start"
    if [[ -s "${LOG_DIR}/tinyproxy.stderr" ]]; then
      cat "${LOG_DIR}/tinyproxy.stderr" >&2
    fi
    exit 1
  }
  if ! wait_for_port; then
    log "tinyproxy did not open 127.0.0.1:${PROXY_PORT}"
    if [[ -s "${LOG_DIR}/tinyproxy.stderr" ]]; then
      cat "${LOG_DIR}/tinyproxy.stderr" >&2
    fi
    if [[ -f "$LOG_FILE" ]]; then
      tail -n 40 "$LOG_FILE" >&2 || true
    fi
    exit 1
  fi
  pid="$(proxy_pid || true)"
  log "tinyproxy listening pid=${pid:-unknown} log=${LOG_FILE}"
}

usage() {
  log "usage: $0 {install|start}"
  exit 2
}

main() {
  local cmd="${1:-}"
  case "$cmd" in
    install)
      install_tinyproxy
      write_shell_env
      log "install complete"
      ;;
    start)
      install_tinyproxy
      write_shell_env
      start_proxy
      log "start complete"
      ;;
    *)
      usage
      ;;
  esac
}

main "$@"
